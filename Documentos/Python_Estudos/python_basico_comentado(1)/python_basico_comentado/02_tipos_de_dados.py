# MÓDULO 2: TIPOS DE DADOS
# type() informa o tipo de um valor ou variável.

nome = "Ana"       # str: texto
idade = 19         # int: número inteiro
nota = 8.5         # float: número decimal
aprovado = True    # bool: verdadeiro ou falso

print(type(nome))
print(type(idade))
print(type(nota))
print(type(aprovado))
