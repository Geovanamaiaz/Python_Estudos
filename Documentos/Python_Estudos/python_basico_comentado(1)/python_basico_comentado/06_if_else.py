# MÓDULO 6: CONDIÇÕES COM IF E ELSE
# if executa um bloco quando a condição é verdadeira.
# else executa outro bloco quando a condição é falsa.
# A indentação (espaços no início da linha) é importante em Python.

nota = float(input("Digite sua nota: "))

if nota >= 6:
    print("Aprovado!")  # Executa se nota for maior ou igual a 6.
else:
    print("Reprovado!")  # Executa se nota for menor que 6.
