# MÓDULO 3: OPERADORES MATEMÁTICOS
# Python pode fazer cálculos usando operadores.

a = 10
b = 3

print("Soma:", a + b)                       # Adição
print("Subtração:", a - b)                  # Subtração
print("Multiplicação:", a * b)              # Multiplicação
print("Divisão:", a / b)                    # Divisão comum
print("Divisão inteira:", a // b)            # Parte inteira da divisão
print("Resto:", a % b)                       # Resto da divisão
print("Potência:", a ** b)                   # a elevado a b
