# MÓDULO 11: FUNÇÕES
# Uma função reúne instruções que podem ser reutilizadas.
# def é a palavra usada para definir uma função.
# return devolve um resultado para quem chamou a função.

def somar(a, b):
    return a + b

resultado = somar(4, 6)  # Chama a função com os valores 4 e 6.
print("Resultado:", resultado)
